  Motor_Init();

  /* 只有电角度校准成功，才允许启动电机 */
  if (Motor_Electric_Calibrated == 1U)
  {
    /* 获取校准结束后的初始电角度 */
    float theta_e = Motor_GetElectricAngle_Rad();
    FOC_ThetaStart = theta_e;

    /* 设置零参考电压 */
    Motor_SetPhaseVoltage_dq_SVPWM(0.0f, 0.0f, theta_e, 12.0f);

    Motor_Enable();

    uint32_t start_time = HAL_GetTick();

    while ((uint32_t)(HAL_GetTick() - start_time) < 5000U)
    {

      /* 获取实时电角度 */
      theta_e = Motor_GetElectricAngle_Rad();

      /* 记录当前电角度 */
      FOC_ThetaEnd = theta_e;

      /* 施加q轴参考电压 */
      Motor_SetPhaseVoltage_dq_SVPWM(0.0f, 0.3f, theta_e, 12.0f);

      HAL_Delay(2U);
    }
    /* 实验结束，关闭驱动 */
    Motor_Disable();
    Motor_SetPhaseVoltage_dq_SVPWM(0.0f, 0.0f, 0.0f, 12.0f);
  }   
  /* USER CODE END 2 */

